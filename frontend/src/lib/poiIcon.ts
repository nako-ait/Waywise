/**
 * 目的地分类图标。
 *
 * 目的：地图和时间轴上一眼看出「这是什么类型的点」—— 不用点开就能分辨
 * 摄影点、博物馆、公园、古镇、购物…… 也顺便让每个目的地都有图标，
 * 而不是只有酒店有。
 *
 * 规则按「具体 → 泛化」排序，命中第一条就返回。
 */
const ICON_RULES: Array<[RegExp, string]> = [
  [/夜景|江景/, '🌃'],
  [/古镇|水乡/, '🛶'],
  [/动物园/, '🐼'],
  [/植物/, '🌿'],
  [/博物馆|美术馆|纪念馆/, '🏛'],
  [/园林|古建|寺庙|教堂/, '🏯'],
  [/公园/, '🌳'],
  [/购物|商圈/, '🛍'],
  [/小吃|餐饮|美食/, '🍜'],
  [/咖啡/, '☕'],
  [/观景/, '🗼'],
  [/地标/, '🏙'],
  [/亲子|水族馆/, '🎡'],
  [/校园/, '🎓'],
  [/广场|交通枢纽/, '🚉'],
  [/街区|citywalk|拍照|艺术|文创|工业风|石库门/, '📸'],
  // —— 高德在线搜索结果用的是它自己的 typecode 词表（"风景名胜;旅游景点"这种）——
  // 上面是按预置库的中文标签匹配的规则，这里补上高德的分类词。
  [/风景名胜|旅游景点|景点/, '🏞'],
  [/餐饮|餐厅|快餐厅|咖啡厅/, '🍜'],
  [/商场|购物服务|超市|便利店/, '🛍'],
  [/体育休闲|影剧院|娱乐场所|游乐场/, '🎭'],
  [/住宿服务|宾馆酒店|旅馆/, '🛏'],
  [/交通设施|地铁站|公交站|火车站|机场/, '🚉'],
  [/医疗保健|医院|药店/, '🏥'],
  [/商务住宅|楼宇|公司企业/, '🏢'],
]

export function poiIcon(tags?: string[] | null): string {
  if (tags?.length) {
    for (const [pattern, icon] of ICON_RULES) {
      if (tags.some((tag) => pattern.test(tag))) return icon
    }
  }
  return '📍'
}
